#!/bin/bash

set -e

DEVICE=g2mv
VENDOR=lge
OUT=../../../vendor/$VENDOR/$DEVICE

cd "$(dirname "$0")"
mkdir -p "$OUT"

cat > "$OUT/Android.mk" <<EOF
LOCAL_PATH := \$(call my-dir)
EOF

{
    echo '# Copyright (C) 2026 The CyanogenMod Project'
    echo '# Auto-generated by device/lge/g2mv/setup-makefiles.sh'
    echo
    echo 'PRODUCT_COPY_FILES += \'
    awk -v prefix="vendor/$VENDOR/$DEVICE/proprietary/" '
        !/^[[:space:]]*(#|$)/ { files[++count] = $0 }
        END {
            for (i = 1; i <= count; i++)
                printf "    %s%s:%s%s\n", prefix, files[i], files[i],
                       (i < count ? " \\" : "")
        }
    ' proprietary-files.txt
} > "$OUT/$DEVICE-vendor.mk"
